const PublicContractSchema = "frostgrove.i18n.public-contract/v1"

const (
	PublicTypeScriptGenerator = "frostgrove.i18n.typescript/v1"
	PublicValueContract       = "frostgrove.i18n.json-scalars/v1"
	PublicTypeScriptTarget    = "ES2020"
	PublicWireFormat          = "json"
)

const publicTypeScriptHeader = "// Code generated by github.com/frostgrove/vv/i18n.ExportPublic. Types only; formatting parity is not provided. DO NOT EDIT.\n\ndeclare const frostgroveI18nScalar: unique symbol;\ntype FrostgroveI18nScalar<Name extends string> = { readonly [frostgroveI18nScalar]: Name };\nexport type Int64String = string & FrostgroveI18nScalar<\"int64\">;\nexport type UInt64String = string & FrostgroveI18nScalar<\"uint64\">;\nexport type BigIntegerString = string & FrostgroveI18nScalar<\"big-integer\">;\nexport type DecimalString = string & FrostgroveI18nScalar<\"decimal\">;\nexport type CurrencyCode = string & FrostgroveI18nScalar<\"iso-4217\">;\nexport type Instant = string & FrostgroveI18nScalar<\"rfc3339-instant\">;\nexport type CalendarDate = Readonly<{ year: number; month: number; day: number }> & FrostgroveI18nScalar<\"calendar-date\">;\nexport type FormattingParity = false;\n"
const publicTypeScriptMoney = "export interface MoneyValue { readonly amount: DecimalString; readonly currency: CurrencyCode; }\n"
const publicTypeScriptFooter = "}\n\nexport type MessageID = keyof MessageContracts;\n"

type PublicExport struct {
	TypeScript []byte
	Manifest   []byte
	Address    string
}

type PublicExportSpec struct {
	MaxOutputBytes int
}

func ExportPublic(snapshot *Snapshot) (PublicExport, error) {
	return ExportPublicContext(context.Background(), snapshot, PublicExportSpec{})
}

func ExportPublicContext(ctx context.Context, snapshot *Snapshot, spec PublicExportSpec) (PublicExport, error) {
	return exportPublicContext(ctx, snapshot, spec, expectedPublicExportAddressContext)
}

func exportPublicContext(ctx context.Context, snapshot *Snapshot, spec PublicExportSpec, address func(context.Context, []byte, []byte) (string, error)) (PublicExport, error) {
	return exportPublicContextWithMessages(ctx, snapshot, spec, address, publicContractMessagesContext)
}

func exportPublicContextWithMessages(ctx context.Context, snapshot *Snapshot, spec PublicExportSpec, address func(context.Context, []byte, []byte) (string, error), messagesFromSnapshot func(context.Context, *Snapshot) ([]publicContractMessage, error)) (PublicExport, error) {
	if ctx == nil {
		return PublicExport{}, fmt.Errorf("%w: public export context is nil", ErrInvalidCatalog)
	}
	if err := ctx.Err(); err != nil {
		return PublicExport{}, err
	}
	if snapshot == nil {
		return PublicExport{}, fmt.Errorf("%w: snapshot is nil", ErrInvalidCatalog)
	}
	maximum := spec.MaxOutputBytes
	if maximum == 0 || maximum > snapshot.limits.MaxCatalogBytes {
		maximum = snapshot.limits.MaxCatalogBytes
	}
	if maximum < 1 {
		return PublicExport{}, fmt.Errorf("%w: public export output limit must be positive", ErrLimitExceeded)
	}
	manifestSize, typeScriptSize, err := measurePublicExportContext(ctx, snapshot, maximum)
	if err != nil {
		return PublicExport{}, err
	}
	messages, err := messagesFromSnapshot(ctx, snapshot)
	if err != nil {
		return PublicExport{}, err
	}
	manifest := publicContractManifest{
		Schema:           PublicContractSchema,
		Profile:          snapshot.Profile(),
		Generator:        PublicTypeScriptGenerator,
		ValueContract:    PublicValueContract,
		TypeScriptTarget: PublicTypeScriptTarget,
		WireFormat:       PublicWireFormat,
		Capabilities:     publicCapabilities(snapshot),
		FormattingParity: false,
		Messages:         messages,
	}
	manifestBytes, err := marshalPublicManifestContext(ctx, manifest, maximum)
	if err != nil {
		return PublicExport{}, err
	}
	typeScript, err := publicTypeScriptContext(ctx, messages, maximum)
	if err != nil {
		return PublicExport{}, err
	}
	if len(manifestBytes) != manifestSize || len(typeScript) != typeScriptSize {
		return PublicExport{}, fmt.Errorf("%w: public contract export size changed during materialization", ErrInvalidCatalog)
	}
	addressValue, err := address(ctx, manifestBytes, typeScript)
	if err != nil {
		return PublicExport{}, err
	}
	return PublicExport{
		TypeScript: typeScript,
		Manifest:   manifestBytes,
		Address:    addressValue,
	}, nil
}

func preflightPublicExport(ctx context.Context, snapshot *Snapshot, maximum int) error {
	_, _, err := measurePublicExportContext(ctx, snapshot, maximum)
	return err
}

func measurePublicExportContext(ctx context.Context, snapshot *Snapshot, maximum int) (int, int, error) {
	manifestLimits := ArtifactLimits{MaxBytes: maximum, MaxDepth: maximumArtifactDepth, MaxMembers: maximumArtifactMembers}
	manifestCounter := artifactFloorCounter{limits: manifestLimits, ctx: ctx}
	manifest := publicContractManifest{
		Schema: PublicContractSchema, Profile: snapshot.profile, Generator: PublicTypeScriptGenerator,
		ValueContract: PublicValueContract, TypeScriptTarget: PublicTypeScriptTarget, WireFormat: PublicWireFormat,
		Capabilities: []string{}, FormattingParity: false, Messages: []publicContractMessage{},
	}
	fail := func() (int, int, error) {
		if manifestCounter.err != nil {
			return 0, 0, manifestCounter.err
		}
		return 0, 0, fmt.Errorf("%w: public contract export exceeds %d bytes", ErrLimitExceeded, maximum)
	}
	if !manifestCounter.addValue(manifest, 1) {
		return fail()
	}
	typeScriptCounter := newContextBoundedTextCounter(ctx, maximum)
	writePublicTypeScriptHeader(typeScriptCounter, false)
	if err := typeScriptCounter.Err(); err != nil {
		return 0, 0, err
	}
	if typeScriptCounter.Overflow() {
		return fail()
	}
	capabilityIndex := 0
	for capability := range snapshot.capabilities {
		if err := ctx.Err(); err != nil {
			return 0, 0, err
		}
		if !manifestCounter.addArrayValue(capability.String(), capabilityIndex, 3) {
			return fail()
		}
		capabilityIndex++
	}
	typeNames := make(map[string]string)
	usesMoney := false
	messageIndex := 0
	for key, record := range snapshot.records {
		if err := ctx.Err(); err != nil {
			return 0, 0, err
		}
		if record == nil {
			return 0, 0, fmt.Errorf("%w: public message %q has no contract", ErrInvalidCatalog, key)
		}
		descriptor := record.descriptor
		if !descriptor.Public {
			continue
		}
		typeName := goExportedIdentifier(string(key), "Message") + "Args"
		if previous, exists := typeNames[typeName]; exists {
			return 0, 0, fmt.Errorf("%w: public TypeScript name %q collides for %q and %q", ErrInvalidCatalog, typeName, previous, key)
		}
		typeNames[typeName] = string(key)
		message := publicContractMessage{
			ID: string(key), Revision: descriptor.Revision, Digest: record.contractHash,
			Output: descriptor.Output.String(), Markup: descriptor.Markup,
			Arguments: []publicContractArgument{}, typeName: typeName,
		}
		if !manifestCounter.addArrayValue(message, messageIndex, 3) {
			return fail()
		}
		writePublicTypeScriptInterfaceStart(typeScriptCounter, typeName)
		for argumentIndex, argument := range descriptor.Arguments {
			if err := ctx.Err(); err != nil {
				return 0, 0, err
			}
			encoded := publicContractArgument{
				Name: argument.Name, Type: argument.Type.String(), Required: argument.Required,
				Nullable: argument.Nullable, Values: argument.Values,
			}
			if !manifestCounter.addArrayValue(encoded, argumentIndex, 5) {
				return fail()
			}
			if err := writePublicTypeScriptArgumentContext(ctx, typeScriptCounter, encoded, maximum); err != nil {
				return 0, 0, err
			}
			usesMoney = usesMoney || argument.Type == TypeMoney
		}
		writePublicTypeScriptInterfaceEnd(typeScriptCounter)
		messageIndex++
		if typeScriptCounter.Overflow() {
			return fail()
		}
	}
	if usesMoney {
		writePublicTypeScriptMoney(typeScriptCounter)
	}
	writePublicTypeScriptContractsStart(typeScriptCounter)
	for key, record := range snapshot.records {
		if err := ctx.Err(); err != nil {
			return 0, 0, err
		}
		if record == nil || !record.descriptor.Public {
			continue
		}
		if err := writePublicTypeScriptContractContext(ctx, typeScriptCounter, string(key), record.descriptor.Revision, record.contractHash, record.descriptor.Output.String(), goExportedIdentifier(string(key), "Message")+"Args", maximum); err != nil {
			return 0, 0, err
		}
		if typeScriptCounter.Overflow() {
			return fail()
		}
	}
	writePublicTypeScriptFooter(typeScriptCounter)
	if err := typeScriptCounter.Err(); err != nil {
		return 0, 0, err
	}
	if typeScriptCounter.Overflow() {
		return fail()
	}
	if err := ctx.Err(); err != nil {
		return 0, 0, err
	}
	return manifestCounter.written, typeScriptCounter.Len(), nil
}

func marshalPublicManifest(manifest publicContractManifest, maximum int) ([]byte, error) {
	return marshalPublicManifestContext(context.Background(), manifest, maximum)
}

func marshalPublicManifestContext(ctx context.Context, manifest publicContractManifest, maximum int) ([]byte, error) {
	limits, err := checkedArtifactLimits(ArtifactLimits{MaxBytes: maximum, MaxDepth: maximumArtifactDepth, MaxMembers: maximumArtifactMembers})
	if err != nil {
		return nil, err
	}
	encoder := boundedArtifactJSON{bytes: make([]byte, 0, min(maximum, 32<<10)), limits: limits, ctx: ctx}
	if err := encoder.value(reflect.ValueOf(manifest), 1); err != nil {
		if errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded) {
			return nil, err
		}
		if errors.Is(err, ErrLimitExceeded) {
			return nil, fmt.Errorf("%w: public manifest exceeds %d bytes", ErrLimitExceeded, maximum)
		}
		return nil, fmt.Errorf("%w: public manifest: %v", ErrInvalidCatalog, err)
	}
	return encoder.bytes, nil
}

type publicContractManifest struct {
	Schema           string                  `json:"schema"`
	Profile          string                  `json:"profile"`
	Generator        string                  `json:"generator"`
	ValueContract    string                  `json:"valueContract"`
	TypeScriptTarget string                  `json:"typeScriptTarget"`
	WireFormat       string                  `json:"wireFormat"`
	Capabilities     []string                `json:"capabilities"`
	FormattingParity bool                    `json:"formattingParity"`
	Messages         []publicContractMessage `json:"messages"`
}

type publicContractMessage struct {
	ID        string                   `json:"id"`
	Revision  string                   `json:"revision"`
	Digest    string                   `json:"digest"`
	Output    string                   `json:"output"`
	Markup    []string                 `json:"markup,omitempty"`
	Arguments []publicContractArgument `json:"arguments"`
	typeName  string
}

type publicContractArgument struct {
	Name     string   `json:"name"`
	Type     string   `json:"type"`
	Required bool     `json:"required"`
	Nullable bool     `json:"nullable"`
	Values   []string `json:"values,omitempty"`
}

func publicContractMessages(snapshot *Snapshot) ([]publicContractMessage, error) {
	return publicContractMessagesContext(context.Background(), snapshot)
}

func publicContractMessagesContext(ctx context.Context, snapshot *Snapshot) ([]publicContractMessage, error) {
	messages := make([]publicContractMessage, 0)
	typeNames := make(map[string]string)
	keys, err := snapshotKeysContext(ctx, snapshot)
	if err != nil {
		return nil, err
	}
	for _, key := range keys {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		descriptor, ok := snapshot.Descriptor(key)
		if !ok || !descriptor.Public {
			continue
		}
		contract, ok := snapshot.ContractRef(key)
		if !ok {
			return nil, fmt.Errorf("%w: public message %q has no contract", ErrInvalidCatalog, key)
		}
		typeName := goExportedIdentifier(string(key), "Message") + "Args"
		if previous, exists := typeNames[typeName]; exists {
			return nil, fmt.Errorf("%w: public TypeScript name %q collides for %q and %q", ErrInvalidCatalog, typeName, previous, key)
		}
		typeNames[typeName] = string(key)
		message := publicContractMessage{
			ID:        string(key),
			Revision:  contract.Revision,
			Digest:    contract.Digest,
			Output:    descriptor.Output.String(),
			Markup:    descriptor.Markup,
			Arguments: make([]publicContractArgument, len(descriptor.Arguments)),
			typeName:  typeName,
		}
		for index, argument := range descriptor.Arguments {
			message.Arguments[index] = publicContractArgument{
				Name:     argument.Name,
				Type:     argument.Type.String(),
				Required: argument.Required,
				Nullable: argument.Nullable,
				Values:   argument.Values,
			}
		}
		messages = append(messages, message)
	}
	return messages, nil
}

func publicTypeScript(messages []publicContractMessage, maximum int) ([]byte, error) {
	return publicTypeScriptContext(context.Background(), messages, maximum)
}

func publicTypeScriptContext(ctx context.Context, messages []publicContractMessage, maximum int) ([]byte, error) {
	source := newContextBoundedTextBuilder(ctx, maximum)
	usesMoney, err := publicContractsUseContext(ctx, messages, TypeMoney)
	if err != nil {
		return nil, err
	}
	writePublicTypeScriptHeader(source, usesMoney)
	for _, message := range messages {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		writePublicTypeScriptInterfaceStart(source, message.typeName)
		for _, argument := range message.Arguments {
			if err := writePublicTypeScriptArgumentContext(ctx, source, argument, maximum); err != nil {
				return nil, err
			}
		}
		writePublicTypeScriptInterfaceEnd(source)
	}
	writePublicTypeScriptContractsStart(source)
	for _, message := range messages {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		if err := writePublicTypeScriptContractContext(ctx, source, message.ID, message.Revision, message.Digest, message.Output, message.typeName, maximum); err != nil {
			return nil, err
		}
	}
	writePublicTypeScriptFooter(source)
	if err := source.Err(); err != nil {
		return nil, err
	}
	if source.Overflow() {
		return nil, fmt.Errorf("%w: public TypeScript exceeds %d bytes", ErrLimitExceeded, maximum)
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	result := []byte(source.String())
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	return result, nil
}

func writePublicTypeScriptHeader(source boundedStringWriter, usesMoney bool) {
	source.WriteString(publicTypeScriptHeader)
	if usesMoney {
		writePublicTypeScriptMoney(source)
	}
	source.WriteString("\n")
}

func writePublicTypeScriptMoney(source boundedStringWriter) {
	source.WriteString(publicTypeScriptMoney)
}

func writePublicTypeScriptInterfaceStart(source boundedStringWriter, typeName string) {
	fmt.Fprintf(source, "export interface %s {\n", typeName)
}

func writePublicTypeScriptInterfaceEnd(source boundedStringWriter) {
	source.WriteString("}\n\n")
}

func writePublicTypeScriptContractsStart(source boundedStringWriter) {
	source.WriteString("export interface MessageContracts {\n")
}

func writePublicTypeScriptFooter(source boundedStringWriter) {
	source.WriteString(publicTypeScriptFooter)
}

func writePublicTypeScriptArgumentContext(ctx context.Context, source boundedStringWriter, argument publicContractArgument, maximum int) error {
	source.WriteString("readonly ")
	if err := writeTypeScriptStringContext(ctx, source, argument.Name, maximum); err != nil {
		return err
	}
	if !argument.Required {
		source.WriteString("?")
	}
	source.WriteString(": ")
	if err := writePublicTypeScriptArgumentTypeContext(ctx, source, argument, maximum); err != nil {
		return err
	}
	if argument.Nullable {
		source.WriteString(" | null")
	}
	source.WriteString(";\n")
	return ctx.Err()
}

func writePublicTypeScriptArgumentTypeContext(ctx context.Context, source boundedStringWriter, argument publicContractArgument, maximum int) error {
	var scalar string
	switch argument.Type {
	case TypeText.String():
		scalar = "string"
	case TypeBool.String():
		scalar = "boolean"
	case TypeInteger.String():
		scalar = "Int64String"
	case TypeUnsignedInteger.String():
		scalar = "UInt64String"
	case TypeBigInteger.String():
		scalar = "BigIntegerString"
	case TypeDecimal.String():
		scalar = "DecimalString"
	case TypeMoney.String():
		scalar = "MoneyValue"
	case TypeDate.String():
		scalar = "CalendarDate"
	case TypeInstant.String():
		scalar = "Instant"
	case TypeEnum.String():
		for index, value := range argument.Values {
			if err := ctx.Err(); err != nil {
				return err
			}
			if index > 0 {
				source.WriteString(" | ")
			}
			if err := writeTypeScriptStringContext(ctx, source, value, maximum); err != nil {
				return err
			}
		}
		return ctx.Err()
	default:
		return fmt.Errorf("%w: unsupported public argument type %q", ErrInvalidCatalog, argument.Type)
	}
	source.WriteString(scalar)
	return ctx.Err()
}

func writePublicTypeScriptContractContext(ctx context.Context, source boundedStringWriter, id, revision, digest, output, typeName string, maximum int) error {
	source.WriteString("readonly ")
	for index, value := range []string{id, revision, digest, output} {
		if err := writeTypeScriptStringContext(ctx, source, value, maximum); err != nil {
			return err
		}
		switch index {
		case 0:
			source.WriteString(": { readonly revision: ")
		case 1:
			source.WriteString("; readonly digest: ")
		case 2:
			source.WriteString("; readonly output: ")
		case 3:
			fmt.Fprintf(source, "; readonly args: %s };\n", typeName)
		}
	}
	return ctx.Err()
}

func writeTypeScriptStringContext(ctx context.Context, source boundedStringWriter, value string, maximum int) error {
	encoder := boundedArtifactJSON{
		limits: ArtifactLimits{MaxBytes: maximum, MaxDepth: maximumArtifactDepth, MaxMembers: maximumArtifactMembers},
		ctx:    ctx,
	}
	if counter, ok := source.(*boundedTextCounter); ok {
		encoder.countOnly = true
		if err := encoder.writeString(value); err != nil {
			return err
		}
		counter.reserve(encoder.written)
		return counter.Err()
	}
	encoder.bytes = make([]byte, 0, min(maximum, len(value)+2))
	if err := encoder.writeString(value); err != nil {
		return err
	}
	_, _ = source.Write(encoder.bytes)
	return ctx.Err()
}

func publicContractsUse(messages []publicContractMessage, argumentType ArgumentType) bool {
	used, _ := publicContractsUseContext(context.Background(), messages, argumentType)
	return used
}

func publicContractsUseContext(ctx context.Context, messages []publicContractMessage, argumentType ArgumentType) (bool, error) {
	want := argumentType.String()
	for _, message := range messages {
		if err := ctx.Err(); err != nil {
			return false, err
		}
		for _, argument := range message.Arguments {
			if argument.Type == want {
				return true, nil
			}
		}
	}
	return false, nil
}

func publicTypeScriptArgumentType(argument publicContractArgument, maximum int) (string, error) {
	return publicTypeScriptArgumentTypeContext(context.Background(), argument, maximum)
}

func publicTypeScriptArgumentTypeContext(ctx context.Context, argument publicContractArgument, maximum int) (string, error) {
	switch argument.Type {
	case TypeText.String():
		return "string", nil
	case TypeBool.String():
		return "boolean", nil
	case TypeInteger.String():
		return "Int64String", nil
	case TypeUnsignedInteger.String():
		return "UInt64String", nil
	case TypeBigInteger.String():
		return "BigIntegerString", nil
	case TypeDecimal.String():
		return "DecimalString", nil
	case TypeMoney.String():
		return "MoneyValue", nil
	case TypeDate.String():
		return "CalendarDate", nil
	case TypeInstant.String():
		return "Instant", nil
	case TypeEnum.String():
		values := newContextBoundedTextBuilder(ctx, maximum)
		for index, value := range argument.Values {
			if err := ctx.Err(); err != nil {
				return "", err
			}
			quoted, err := typeScriptString(value)
			if err != nil {
				return "", err
			}
			if index > 0 {
				values.WriteString(" | ")
			}
			values.WriteString(quoted)
		}
		if err := values.Err(); err != nil {
			return "", err
		}
		if values.Overflow() {
			return "", fmt.Errorf("%w: public TypeScript enum exceeds %d bytes", ErrLimitExceeded, maximum)
		}
		return values.String(), nil
	default:
		return "", fmt.Errorf("%w: unsupported public argument type %q", ErrInvalidCatalog, argument.Type)
	}
}

func publicCapabilities(snapshot *Snapshot) []string {
	capabilities := make([]string, 0, len(snapshot.capabilities))
	for capability := range snapshot.capabilities {
		capabilities = append(capabilities, capability.String())
	}
	slices.Sort(capabilities)
	return capabilities
}

func ExpectedPublicExportAddress(manifest, typeScript []byte) string {
	address, _ := ExpectedPublicExportAddressContext(context.Background(), manifest, typeScript)
	return address
}

func ExpectedPublicExportAddressContext(ctx context.Context, manifest, typeScript []byte) (string, error) {
	if ctx == nil {
		return "", fmt.Errorf("%w: public export address context is nil", ErrInvalidCatalog)
	}
	hash := sha256.New()
	for _, field := range []struct {
		name  []byte
		value []byte
	}{
		{name: []byte("domain"), value: []byte("frostgrove.i18n.public-export-address/v1")},
		{name: []byte("manifest"), value: manifest},
		{name: []byte("typescript"), value: typeScript},
	} {
		if err := writePublicDigestBytesContext(ctx, hash.Write, field.name); err != nil {
			return "", err
		}
		if err := writePublicDigestBytesContext(ctx, hash.Write, field.value); err != nil {
			return "", err
		}
	}
	return "sha256:" + hex.EncodeToString(hash.Sum(nil)), nil
}

func expectedPublicExportAddressContext(ctx context.Context, manifest, typeScript []byte) (string, error) {
	return ExpectedPublicExportAddressContext(ctx, manifest, typeScript)
}

func writePublicDigestBytesContext(ctx context.Context, write func([]byte) (int, error), value []byte) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	prefix := strconv.AppendInt(nil, int64(len(value)), 10)
	prefix = append(prefix, ':')
	_, _ = write(prefix)
	for len(value) != 0 {
		if err := ctx.Err(); err != nil {
			return err
		}
		chunk := min(len(value), 32<<10)
		_, _ = write(value[:chunk])
		value = value[chunk:]
	}
	_, _ = write([]byte{'\n'})
	return ctx.Err()
}

func typeScriptString(value string) (string, error) {
	encoded, err := json.Marshal(value)
	if err != nil {
		return "", fmt.Errorf("%w: TypeScript string: %v", ErrInvalidCatalog, err)
	}
	return string(encoded), nil
}
