package i18n

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"go/token"
	"strconv"
	"strings"
)

type GoGeneratorSpec struct {
	Package        string
	MaxOutputBytes int
}

func GenerateGo(snapshot *Snapshot, spec GoGeneratorSpec) ([]byte, error) {
	return GenerateGoContext(context.Background(), snapshot, spec)
}

func GenerateGoContext(ctx context.Context, snapshot *Snapshot, spec GoGeneratorSpec) ([]byte, error) {
	return generateGoContext(ctx, snapshot, spec, format.Source)
}

func generateGoContext(ctx context.Context, snapshot *Snapshot, spec GoGeneratorSpec, formatSource func([]byte) ([]byte, error)) ([]byte, error) {
	if ctx == nil {
		return nil, fmt.Errorf("%w: generation context is nil", ErrInvalidCatalog)
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if snapshot == nil {
		return nil, fmt.Errorf("%w: snapshot is nil", ErrInvalidCatalog)
	}
	maximum := spec.MaxOutputBytes
	if maximum == 0 || maximum > snapshot.limits.MaxCatalogBytes {
		maximum = snapshot.limits.MaxCatalogBytes
	}
	if maximum < 1 {
		return nil, fmt.Errorf("%w: generated Go output limit must be positive", ErrLimitExceeded)
	}
	if len(spec.Package) > snapshot.limits.MaxIdentifierBytes {
		return nil, fmt.Errorf("%w: Go package exceeds %d bytes", ErrLimitExceeded, snapshot.limits.MaxIdentifierBytes)
	}
	if !token.IsIdentifier(spec.Package) {
		return nil, fmt.Errorf("%w: invalid Go package %q", ErrInvalidCatalog, spec.Package)
	}
	if err := preflightGoGeneration(ctx, snapshot, maximum); err != nil {
		return nil, err
	}
	messages, needsBig, needsTime, needsMoney, err := generatedGoMessagesContext(ctx, snapshot)
	if err != nil {
		return nil, err
	}

	counter := newContextBoundedTextCounter(ctx, maximum)
	if err := writeGeneratedGoContext(ctx, counter, spec.Package, messages, needsBig, needsTime, needsMoney); err != nil {
		return nil, err
	}
	if err := counter.Err(); err != nil {
		return nil, err
	}
	if counter.Overflow() {
		return nil, fmt.Errorf("%w: generated Go source exceeds %d bytes", ErrLimitExceeded, maximum)
	}
	source := newContextBoundedTextBuilder(ctx, maximum)
	if err := writeGeneratedGoContext(ctx, source, spec.Package, messages, needsBig, needsTime, needsMoney); err != nil {
		return nil, err
	}
	if err := source.Err(); err != nil {
		return nil, err
	}
	if source.Overflow() || source.Len() != counter.Len() {
		return nil, fmt.Errorf("%w: generated Go source exceeds %d bytes", ErrLimitExceeded, maximum)
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	formatted, err := formatSource([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("%w: generated Go source: %v", ErrInvalidCatalog, err)
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if len(formatted) > maximum {
		return nil, fmt.Errorf("%w: generated Go source exceeds %d bytes", ErrLimitExceeded, maximum)
	}
	return formatted, nil
}

func writeGeneratedGoContext(ctx context.Context, source boundedStringWriter, packageName string, messages []generatedGoMessage, needsBig, needsTime, needsMoney bool) error {
	source.WriteString("// Code generated by github.com/frostgrove/vv/i18n.GenerateGo. DO NOT EDIT.\n\n")
	source.WriteString("package ")
	source.WriteString(packageName)
	source.WriteString("\n\n")
	if needsBig {
		source.WriteString("import \"math/big\"\n\n")
	}
	if needsTime {
		source.WriteString("import \"time\"\n\n")
	}
	source.WriteString("import vvi18n \"github.com/frostgrove/vv/i18n\"\n\n")
	if needsMoney {
		source.WriteString("type Money struct {\n\tAmount string\n\n\tCurrency string\n}\n\n")
	}
	source.WriteString("type Catalog struct {\n")
	for index, message := range messages {
		if err := ctx.Err(); err != nil {
			return err
		}
		if index > 0 {
			source.WriteString("\n")
		}
		fmt.Fprintf(source, "\t%s vvi18n.Definition[%s]\n", message.field, message.argsType)
	}
	source.WriteString("}\n\n")

	for _, message := range messages {
		if err := ctx.Err(); err != nil {
			return err
		}
		for _, argument := range message.arguments {
			if err := ctx.Err(); err != nil {
				return err
			}
			if argument.spec.Type != TypeEnum {
				continue
			}
			fmt.Fprintf(source, "type %s string\n\n", argument.baseType)
			for valueIndex, value := range argument.spec.Values {
				if err := ctx.Err(); err != nil {
					return err
				}
				fmt.Fprintf(source, "const %s %s = %s\n\n", argument.enumConstants[valueIndex], argument.baseType, strconv.Quote(value))
			}
		}
		fmt.Fprintf(source, "type %s struct {\n", message.argsType)
		for index, argument := range message.arguments {
			if err := ctx.Err(); err != nil {
				return err
			}
			if index > 0 {
				source.WriteString("\n")
			}
			fmt.Fprintf(source, "\t%s %s\n", argument.field, argument.fieldType)
		}
		source.WriteString("}\n\n")
	}

	source.WriteString("func NewCatalog(snapshot *vvi18n.Snapshot) (Catalog, error) {\n\tvar catalog Catalog\n")
	if len(messages) != 0 {
		source.WriteString("\tvar err error\n")
	}
	for _, message := range messages {
		if err := ctx.Err(); err != nil {
			return err
		}
		fmt.Fprintf(source, "\tcatalog.%s, err = vvi18n.Define(snapshot, vvi18n.DefinitionSpec[%s]{Contract: vvi18n.ContractRef{Key: vvi18n.Key(%s), Revision: %s, Digest: %s}, Encode: encode%s})\n", message.field, message.argsType, strconv.Quote(string(message.contract.Key)), strconv.Quote(message.contract.Revision), strconv.Quote(message.contract.Digest), message.name)
		source.WriteString("\tif err != nil {\n\t\treturn Catalog{}, err\n\t}\n")
	}
	source.WriteString("\treturn catalog, nil\n}")
	if len(messages) == 0 {
		source.WriteString("\n")
	} else {
		source.WriteString("\n\n")
	}

	for messageIndex, message := range messages {
		if err := ctx.Err(); err != nil {
			return err
		}
		fmt.Fprintf(source, "func encode%s(value %s) ([]vvi18n.Argument, error) {\n", message.name, message.argsType)
		if len(message.arguments) == 0 {
			source.WriteString("\treturn nil, nil\n}")
			if messageIndex == len(messages)-1 {
				source.WriteString("\n")
			} else {
				source.WriteString("\n\n")
			}
			continue
		}
		fmt.Fprintf(source, "\targuments := make([]vvi18n.Argument, 0, %d)\n", len(message.arguments))
		for _, argument := range message.arguments {
			if err := ctx.Err(); err != nil {
				return err
			}
			access := "value." + argument.field
			if argument.spec.Required && !argument.spec.Nullable {
				fmt.Fprintf(source, "\targuments = append(arguments, %s)\n", generatedArgumentExpression(argument.spec, access))
				continue
			}
			fmt.Fprintf(source, "\tif fieldValue, ok := %s.Get(); ok {\n", access)
			fmt.Fprintf(source, "\t\targuments = append(arguments, %s)\n", generatedArgumentExpression(argument.spec, "fieldValue"))
			fmt.Fprintf(source, "\t} else if %s.IsNull() {\n", access)
			fmt.Fprintf(source, "\t\targuments = append(arguments, vvi18n.Null(%s))\n\t}\n", strconv.Quote(argument.spec.Name))
		}
		source.WriteString("\treturn arguments, nil\n}")
		if messageIndex == len(messages)-1 {
			source.WriteString("\n")
		} else {
			source.WriteString("\n\n")
		}
	}
	return ctx.Err()
}

func preflightGoGeneration(ctx context.Context, snapshot *Snapshot, maximum int) error {
	remaining := maximum
	consume := func(size int) bool {
		if size < 0 || size > remaining {
			return false
		}
		remaining -= size
		return true
	}
	if !consume(64) {
		return fmt.Errorf("%w: generated Go source exceeds %d bytes", ErrLimitExceeded, maximum)
	}
	for key, record := range snapshot.records {
		if err := ctx.Err(); err != nil {
			return err
		}
		minimum := 128 + len(key) + len(record.descriptor.Revision) + len(record.contractHash)
		for _, argument := range record.descriptor.Arguments {
			if err := ctx.Err(); err != nil {
				return err
			}
			minimum += 16 + len(argument.Name)
			for _, value := range argument.Values {
				if err := ctx.Err(); err != nil {
					return err
				}
				minimum += len(value)
			}
		}
		if !consume(minimum) {
			return fmt.Errorf("%w: generated Go source exceeds %d bytes", ErrLimitExceeded, maximum)
		}
	}
	return nil
}

type generatedGoMessage struct {
	name      string
	field     string
	argsType  string
	contract  ContractRef
	arguments []generatedGoArgument
}

type generatedGoArgument struct {
	spec          ArgumentSpec
	field         string
	baseType      string
	fieldType     string
	enumConstants []string
}

type generatedEnumLocation struct {
	message  int
	argument int
}

type generatedConstantLocation struct {
	message  int
	argument int
	value    int
}

func generatedGoMessagesContext(ctx context.Context, snapshot *Snapshot) ([]generatedGoMessage, bool, bool, bool, error) {
	keys, err := snapshotKeysContext(ctx, snapshot)
	if err != nil {
		return nil, false, false, false, err
	}
	keyStrings, err := keysToStringsContext(ctx, keys)
	if err != nil {
		return nil, false, false, false, err
	}
	identifiers, err := uniqueGeneratedIdentifiersContext(ctx, keyStrings, "Message")
	if err != nil {
		return nil, false, false, false, err
	}
	fieldIdentifiers, err := uniqueGeneratedIdentifiersContext(ctx, keyStrings, "")
	if err != nil {
		return nil, false, false, false, err
	}
	messages := make([]generatedGoMessage, 0, len(keys))
	needsBig := false
	needsTime := false
	needsMoney := false
	for index, key := range keys {
		if err := ctx.Err(); err != nil {
			return nil, false, false, false, err
		}
		record, ok := snapshot.records[key]
		if !ok {
			return nil, false, false, false, fmt.Errorf("%w: message %q has no contract", ErrInvalidCatalog, key)
		}
		descriptor := record.descriptor
		contract := ContractRef{Key: key, Revision: descriptor.Revision, Digest: record.contractHash}
		name := identifiers[index]
		message := generatedGoMessage{
			name:     name,
			field:    fieldIdentifiers[index],
			argsType: name + "Args",
			contract: contract,
		}
		argumentNames := make([]string, len(descriptor.Arguments))
		for argumentIndex, argument := range descriptor.Arguments {
			if err := ctx.Err(); err != nil {
				return nil, false, false, false, err
			}
			argumentNames[argumentIndex] = argument.Name
		}
		argumentFields, identifierErr := uniqueGeneratedIdentifiersContext(ctx, argumentNames, "Arg")
		if identifierErr != nil {
			return nil, false, false, false, fmt.Errorf("%w: arguments for %q: %v", ErrInvalidCatalog, key, identifierErr)
		}
		for argumentIndex, argument := range descriptor.Arguments {
			if err := ctx.Err(); err != nil {
				return nil, false, false, false, err
			}
			generated := generatedGoArgument{spec: argument, field: argumentFields[argumentIndex]}
			generated.baseType = generatedGoBaseType(name, generated.field, argument.Type)
			message.arguments = append(message.arguments, generated)
			needsBig = needsBig || argument.Type == TypeBigInteger
			needsTime = needsTime || argument.Type == TypeInstant
			needsMoney = needsMoney || argument.Type == TypeMoney
		}
		messages = append(messages, message)
	}
	if err := finalizeGeneratedGoNames(ctx, messages); err != nil {
		return nil, false, false, false, err
	}
	return messages, needsBig, needsTime, needsMoney, nil
}

func finalizeGeneratedGoNames(ctx context.Context, messages []generatedGoMessage) error {
	reserved := map[string]bool{"Catalog": true, "Money": true, "NewCatalog": true}
	for _, message := range messages {
		if err := ctx.Err(); err != nil {
			return err
		}
		reserved[message.argsType] = true
		reserved["encode"+message.name] = true
	}

	locations := make([]generatedEnumLocation, 0)
	identities := make([]string, 0)
	bases := make([]string, 0)
	for messageIndex := range messages {
		if err := ctx.Err(); err != nil {
			return err
		}
		for argumentIndex := range messages[messageIndex].arguments {
			if err := ctx.Err(); err != nil {
				return err
			}
			argument := &messages[messageIndex].arguments[argumentIndex]
			if argument.spec.Type != TypeEnum {
				continue
			}
			locations = append(locations, generatedEnumLocation{message: messageIndex, argument: argumentIndex})
			identities = append(identities, string(messages[messageIndex].contract.Key)+"\x00"+argument.spec.Name)
			bases = append(bases, argument.baseType)
		}
	}
	enumNames, err := uniqueGeneratedIdentifiersAgainstContext(ctx, identities, bases, reserved)
	if err != nil {
		return fmt.Errorf("%w: generated enum type names: %v", ErrInvalidCatalog, err)
	}
	for index, name := range enumNames {
		if err := ctx.Err(); err != nil {
			return err
		}
		location := locations[index]
		messages[location.message].arguments[location.argument].baseType = name
		reserved[name] = true
	}

	for messageIndex := range messages {
		if err := ctx.Err(); err != nil {
			return err
		}
		for argumentIndex := range messages[messageIndex].arguments {
			if err := ctx.Err(); err != nil {
				return err
			}
			argument := &messages[messageIndex].arguments[argumentIndex]
			argument.fieldType = argument.baseType
			if !argument.spec.Required || argument.spec.Nullable {
				argument.fieldType = "vvi18n.Optional[" + argument.baseType + "]"
			}
		}
	}

	constantLocations := make([]generatedConstantLocation, 0)
	constantIdentities := make([]string, 0)
	constantBases := make([]string, 0)
	for messageIndex := range messages {
		if err := ctx.Err(); err != nil {
			return err
		}
		for argumentIndex := range messages[messageIndex].arguments {
			if err := ctx.Err(); err != nil {
				return err
			}
			argument := &messages[messageIndex].arguments[argumentIndex]
			if argument.spec.Type != TypeEnum {
				continue
			}
			argument.enumConstants = make([]string, len(argument.spec.Values))
			for valueIndex, value := range argument.spec.Values {
				if err := ctx.Err(); err != nil {
					return err
				}
				constantLocations = append(constantLocations, generatedConstantLocation{message: messageIndex, argument: argumentIndex, value: valueIndex})
				constantIdentities = append(constantIdentities, string(messages[messageIndex].contract.Key)+"\x00"+argument.spec.Name+"\x00"+value)
				constantBases = append(constantBases, argument.baseType+goExportedIdentifier(value, "Value"))
			}
		}
	}
	constantNames, err := uniqueGeneratedIdentifiersAgainstContext(ctx, constantIdentities, constantBases, reserved)
	if err != nil {
		return fmt.Errorf("%w: generated enum constant names: %v", ErrInvalidCatalog, err)
	}
	for index, name := range constantNames {
		if err := ctx.Err(); err != nil {
			return err
		}
		location := constantLocations[index]
		messages[location.message].arguments[location.argument].enumConstants[location.value] = name
		reserved[name] = true
	}
	return nil
}

func generatedGoBaseType(messageName, argumentName string, argumentType ArgumentType) string {
	switch argumentType {
	case TypeText, TypeDecimal:
		return "string"
	case TypeBool:
		return "bool"
	case TypeInteger:
		return "int64"
	case TypeUnsignedInteger:
		return "uint64"
	case TypeBigInteger:
		return "*big.Int"
	case TypeMoney:
		return "Money"
	case TypeDate:
		return "vvi18n.DateValue"
	case TypeInstant:
		return "time.Time"
	case TypeEnum:
		return messageName + argumentName + "Enum"
	default:
		return "struct{}"
	}
}

func generatedArgumentExpression(argument ArgumentSpec, access string) string {
	name := strconv.Quote(argument.Name)
	switch argument.Type {
	case TypeText:
		return "vvi18n.Text(" + name + ", " + access + ")"
	case TypeBool:
		return "vvi18n.Bool(" + name + ", " + access + ")"
	case TypeInteger:
		return "vvi18n.Integer(" + name + ", " + access + ")"
	case TypeUnsignedInteger:
		return "vvi18n.UnsignedInteger(" + name + ", " + access + ")"
	case TypeBigInteger:
		return "vvi18n.BigInteger(" + name + ", " + access + ")"
	case TypeDecimal:
		return "vvi18n.Decimal(" + name + ", " + access + ")"
	case TypeMoney:
		return "vvi18n.Money(" + name + ", " + access + ".Amount, " + access + ".Currency)"
	case TypeDate:
		return "vvi18n.Date(" + name + ", " + access + ".Year, " + access + ".Month, " + access + ".Day)"
	case TypeInstant:
		return "vvi18n.Instant(" + name + ", " + access + ")"
	case TypeEnum:
		return "vvi18n.Enum(" + name + ", string(" + access + "))"
	default:
		return "vvi18n.Null(" + name + ")"
	}
}

func keysToStrings(keys []Key) []string {
	values, _ := keysToStringsContext(context.Background(), keys)
	return values
}

func keysToStringsContext(ctx context.Context, keys []Key) ([]string, error) {
	values := make([]string, len(keys))
	for index, key := range keys {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		values[index] = string(key)
	}
	return values, ctx.Err()
}

func uniqueGeneratedIdentifiers(values []string, fallback string) ([]string, error) {
	return uniqueGeneratedIdentifiersContext(context.Background(), values, fallback)
}

func uniqueGeneratedIdentifiersContext(ctx context.Context, values []string, fallback string) ([]string, error) {
	bases := make([]string, len(values))
	for index, value := range values {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		bases[index] = goExportedIdentifier(value, fallback)
	}
	return uniqueGeneratedIdentifiersAgainstContext(ctx, values, bases, nil)
}

func uniqueGeneratedIdentifiersFromBases(values, bases []string) ([]string, error) {
	return uniqueGeneratedIdentifiersAgainst(values, bases, nil)
}

func uniqueGeneratedIdentifiersAgainst(values, bases []string, reserved map[string]bool) ([]string, error) {
	return uniqueGeneratedIdentifiersAgainstContext(context.Background(), values, bases, reserved)
}

func uniqueGeneratedIdentifiersAgainstContext(ctx context.Context, values, bases []string, reserved map[string]bool) ([]string, error) {
	if len(values) != len(bases) {
		return nil, fmt.Errorf("identifier inputs have different lengths")
	}
	result := make([]string, len(bases))
	used := make(map[string]bool, len(bases)+len(reserved))
	for name := range reserved {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		used[name] = true
	}
	for index, base := range bases {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		if used[base] {
			return nil, fmt.Errorf("identifier %q for %q collides with another generated declaration", base, values[index])
		}
		used[base] = true
		result[index] = base
	}
	return result, ctx.Err()
}

func goExportedIdentifier(value, fallback string) string {
	var out strings.Builder
	upper := true
	for _, r := range value {
		if r >= 'a' && r <= 'z' {
			if upper {
				r -= 'a' - 'A'
			}
			out.WriteRune(r)
			upper = false
			continue
		}
		if r >= 'A' && r <= 'Z' {
			out.WriteRune(r)
			upper = false
			continue
		}
		if r >= '0' && r <= '9' {
			if out.Len() == 0 {
				out.WriteByte('X')
			}
			out.WriteRune(r)
			upper = false
			continue
		}
		upper = true
	}
	if out.Len() == 0 {
		out.WriteString(fallback)
	}
	if out.Len() == 0 {
		out.WriteByte('X')
	}
	if !stableReadableIdentifierSource(value) {
		out.WriteByte('X')
		out.WriteString(generatedIdentifierHash(value))
	}
	return out.String()
}

func stableReadableIdentifierSource(value string) bool {
	if value == "" {
		return false
	}
	for _, segment := range strings.Split(value, ".") {
		if segment == "" || segment[0] < 'a' || segment[0] > 'z' {
			return false
		}
		for _, character := range segment[1:] {
			if character >= 'a' && character <= 'z' || character >= '0' && character <= '9' {
				continue
			}
			return false
		}
	}
	return true
}

func generatedIdentifierHash(value string) string {
	sum := sha256.Sum256([]byte(value))
	return hex.EncodeToString(sum[:8])
}
