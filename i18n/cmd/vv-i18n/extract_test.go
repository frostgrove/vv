func writeNamedTestModule(t testing.TB, directory, modulePath string) {
	t.Helper()
	working, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	i18nModule := filepath.Clean(filepath.Join(working, "..", ".."))
	moduleRaw, err := os.ReadFile(filepath.Join(i18nModule, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	parsed, err := modfile.Parse("go.mod", moduleRaw, nil)
	if err != nil {
		t.Fatal(err)
	}
	var requirements strings.Builder
	for _, requirement := range parsed.Require {
		requirements.WriteString("\t" + requirement.Mod.Path + " " + requirement.Mod.Version + " // indirect\n")
	}
	goVersion := "1.26.5"
	if parsed.Go != nil {
		goVersion = parsed.Go.Version
	}
	goMod := "module " + modulePath + "\n\ngo " + goVersion + "\n\nrequire github.com/frostgrove/vv/i18n v0.0.0\n\nrequire (\n" + requirements.String() + ")\n\nreplace github.com/frostgrove/vv/i18n => " + filepath.ToSlash(i18nModule) + "\n"
	writeTestFile(t, filepath.Join(directory, "go.mod"), goMod)
	goSum, err := os.ReadFile(filepath.Join(i18nModule, "go.sum"))
	if err != nil {
		t.Fatal(err)
	}
	writeTestFile(t, filepath.Join(directory, "go.sum"), string(goSum))
}

func tidyTestModule(t testing.TB, directory string) {
	t.Helper()
	runTestGo(t, directory, "mod", "tidy")
}

func runTestGo(t testing.TB, directory string, arguments ...string) {
	t.Helper()
	cache, cleanup, err := newUsageGoCache()
	if err != nil {
		t.Fatal(err)
	}
	defer cleanup()
	environment := goCommandEnvironment(cache)
	filtered := environment[:0]
	for _, value := range environment {
		name, _, _ := strings.Cut(value, "=")
		if name != "GOWORK" && name != "GOFLAGS" {
			filtered = append(filtered, value)
		}
	}
	command := exec.Command("go", arguments...)
	command.Dir = directory
	command.Env = append(filtered, "GOWORK=off", "GOFLAGS=")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("go %s: %v\n%s", strings.Join(arguments, " "), err, output)
	}
}

func quotedGo(value string) string {
	return "`" + strings.ReplaceAll(value, "`", "` + \"`\" + `") + "`"
}
