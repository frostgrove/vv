func TestExtractUsageQualifiesSameRelativePathAcrossModulesDeterministically(t *testing.T) {
	firstRoot := filepath.Join(t.TempDir(), "first")
	secondRoot := filepath.Join(t.TempDir(), "second")
	for _, fixture := range []struct {
		root   string
		module string
		key    string
	}{
		{root: firstRoot, module: "example.test/first", key: "app.first"},
		{root: secondRoot, module: "example.test/second", key: "app.second"},
	} {
		writeNamedTestModule(t, fixture.root, fixture.module)
		writeTestFile(t, filepath.Join(fixture.root, "use.go"), `package sample
import "github.com/frostgrove/vv/i18n"
func use(snapshot *i18n.Snapshot) { _, _ = snapshot.Bind("`+fixture.key+`") }
`)
	}
	first, err := extractUsage(context.Background(), []string{firstRoot, secondRoot}, true)
	if err != nil {
		t.Fatal(err)
	}
	second, err := extractUsage(context.Background(), []string{secondRoot, firstRoot}, true)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(first.Occurrences, second.Occurrences) {
		t.Fatalf("root order changed module-backed locations:\n%+v\n%+v", first.Occurrences, second.Occurrences)
	}
	if first.GoScope == nil || second.GoScope == nil || first.GoScope.SourceDigest != second.GoScope.SourceDigest || !slices.Equal(first.GoScope.Roots, second.GoScope.Roots) {
		t.Fatalf("root order changed scope provenance:\n%+v\n%+v", first.GoScope, second.GoScope)
	}
	wantPaths := []string{"example.test/first/use.go", "example.test/second/use.go"}
	gotPaths := []string{first.Occurrences[0].Path, first.Occurrences[1].Path}
	if !slices.Equal(gotPaths, wantPaths) {
		t.Fatalf("qualified paths = %v, want %v", gotPaths, wantPaths)
	}
}

