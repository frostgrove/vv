func (c *liveCore) exec(ctx context.Context, query string, args ...any) (crud.Result, error) {
	if executor, ok := crud.ExecutorFor(ctx, c.source); ok {
		return executor.Exec(ctx, query, args...)
	}
	return c.source.Exec(ctx, query, args...)
}

func (c *liveCore) query(ctx context.Context, query string, args ...any) (crud.Rows, error) {
	if executor, ok := crud.ExecutorFor(ctx, c.source); ok {
		return executor.Query(ctx, query, args...)
	}
	return c.source.Query(ctx, query, args...)
}

