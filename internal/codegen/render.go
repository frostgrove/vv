const generatedHeader = "// Code generated by vv. DO NOT EDIT."

func (this *generator) render() ([]byte, error) {
	var body bytes.Buffer
	var u used

	for _, name := range this.order {
		m := this.models[name]
		if this.wireOnly {
			s, mu, err := this.renderWire(m)
			if err != nil {
				return nil, err
			}
			body.WriteString(s)
			u.also(mu)
			continue
		}
		if this.withDTO {
			s, mu := this.renderDTO(m)
			body.WriteString(s)
			u.also(mu)
		}
		if this.withMeta {
			s, mu := this.renderMetamodel(m)
			body.WriteString(s)
			u.also(mu)
		}
		if this.withRepo {
			s, mu, err := this.renderRepository(m)
			if err != nil {
				return nil, err
			}
			body.WriteString(s)
			u.also(mu)
		}
		if this.adapter {
			s, mu, err := this.renderAdapter(m)
			if err != nil {
				return nil, err
			}
			body.WriteString(s)
			u.also(mu)
		}
	}
	if this.withDTO {
		body.WriteString(this.renderCoverage())
		u.port = true
	}
	if this.wireOnly {
		body.WriteString(this.renderWireCoverage())
		u.wire = true
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "%s\n\npackage %s\n\n", generatedHeader, this.pkg)

	type generatedImport struct {
		alias string
		path  string
		bare  bool
	}
	byPath := map[string]generatedImport{}
	addImport := func(alias, path string, bare bool) error {
		if path == "" {
			return fmt.Errorf("generated import %s has an empty path", alias)
		}
		if previous, exists := byPath[path]; exists {
			if previous.alias != alias {
				return fmt.Errorf("generated import %q needs incompatible aliases %q and %q", path, previous.alias, alias)
			}
			return nil
		}
		byPath[path] = generatedImport{alias: alias, path: path, bare: bare}
		return nil
	}
	if u.context {
		if err := addImport("context", "context", true); err != nil {
			return nil, err
		}
	}
	if u.http {
		if err := addImport("http", "net/http", true); err != nil {
			return nil, err
		}
	}
	if u.time {
		if err := addImport("time", "time", true); err != nil {
			return nil, err
		}
	}
	if u.crud {
		if err := addImport("crud", this.crudPkg, this.crudPkg == DefaultCrudPkg); err != nil {
			return nil, err
		}
	}
	if u.utils {
		pkg := this.utilsPkg
		if pkg == "" {
			pkg = DefaultUtilsPkg
		}
		if err := addImport("utils", pkg, pkg == DefaultUtilsPkg); err != nil {
			return nil, err
		}
	}
	if u.errs {
		if err := addImport("errs", this.errsPkg, this.errsPkg == DefaultErrsPkg); err != nil {
			return nil, err
		}
	}
	if u.net {
		if err := addImport("crudnet", this.netPkg, this.netPkg == DefaultNetPkg); err != nil {
			return nil, err
		}
	}
	if u.port {
		if err := addImport("port", this.portPkg, this.portPkg == DefaultPortPkg); err != nil {
			return nil, err
		}
	}
	if u.wire {
		pkg := this.wirePkg
		if pkg == "" {
			pkg = DefaultWirePkg
		}
		if err := addImport("wire", pkg, pkg == DefaultWirePkg); err != nil {
			return nil, err
		}
	}
	if u.specs {
		if err := addImport("specs", this.specsPkg, this.specsPkg == DefaultSpecsPkg); err != nil {
			return nil, err
		}
	}
	if u.sqlrepo {
		if err := addImport("sqlrepo", "github.com/frostgrove/vv/crud/sqlrepo", true); err != nil {
			return nil, err
		}
	}
	if this.modelImport != "" {
		if err := addImport(this.modelAlias, this.modelImport, false); err != nil {
			return nil, err
		}
	}

	for alias, path := range this.extraImports(body.String()) {
		if err := addImport(alias, path, false); err != nil {
			return nil, err
		}
	}
	imports := make([]string, 0, len(byPath))
	for _, item := range byPath {
		if item.bare {
			imports = append(imports, fmt.Sprintf("%q", item.path))
		} else {
			imports = append(imports, fmt.Sprintf("%s %q", item.alias, item.path))
		}
	}
	if len(imports) > 0 {
		sort.Strings(imports)
		out.WriteString("import (\n")
		for _, imp := range imports {
			fmt.Fprintf(&out, "\t%s\n", imp)
		}
		out.WriteString(")\n\n")
	}
	out.Write(body.Bytes())

	source, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated code does not parse: %w\n%s", err, out.String())
	}
	return source, nil
}

type used struct{ crud, utils, specs, sqlrepo, time, port, errs, context, http, net, wire bool }

func (this *used) also(o used) {
	this.crud = this.crud || o.crud
	this.utils = this.utils || o.utils
	this.specs = this.specs || o.specs
	this.sqlrepo = this.sqlrepo || o.sqlrepo
	this.time = this.time || o.time
	this.port = this.port || o.port
	this.errs = this.errs || o.errs
	this.context = this.context || o.context
	this.http = this.http || o.http
	this.net = this.net || o.net
	this.wire = this.wire || o.wire
}

func (this *generator) renderRepository(m *model) (string, used, error) {
	pk, ok := m.pk()
	if !ok {
		return "", used{}, fmt.Errorf("%s has no primary key: name it ID/Id or use db:\",pk\" for a non-conventional key", m.Name)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "type %sRepo = crud.Repo[%s, %s, %sUpdate]\n\n", m.Name, this.qual(m.Name), pk.Type, m.Name)
	setting := ""
	for _, f := range m.Fields {
		if f.Tombstone {
			setting = fmt.Sprintf(", sqlrepo.SoftDelete(%q)", f.Name)
			break
		}
	}
	fmt.Fprintf(&b, "var %sRepository = sqlrepo.Define[%s, %s, %sUpdate](\"\"%s)\n\n",
		m.Name, this.qual(m.Name), pk.Type, m.Name, setting)
	fmt.Fprintf(&b, "func New%sRepository(src crud.Source) *%sRepo {\n", m.Name, m.Name)
	fmt.Fprintf(&b, "\treturn %sRepository.Bind(src)\n}\n\n", m.Name)
	return b.String(), used{crud: true, sqlrepo: true}, nil
}

func (this *generator) extraImports(body string) map[string]string {
	need := map[string]string{}
	file, err := parser.ParseFile(token.NewFileSet(), "generated-body.go", "package generated\n"+body, 0)
	if err != nil {
		return need
	}
	ast.Inspect(file, func(node ast.Node) bool {
		selector, ok := node.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		pkg, ok := selector.X.(*ast.Ident)
		if !ok {
			return true
		}

		if pkg.Obj != nil {
			return true
		}
		if path, known := this.imports[pkg.Name]; known {
			need[pkg.Name] = path
		}
		return true
	})
	return need
}

func updateFields(m *model) []field {
	var out []field
	for _, f := range m.Fields {
		if f.Skip || f.isRelation() || f.PK || f.Generated || f.Immutable || f.ServerOwned || f.Tombstone || f.Version {
			continue
		}
		out = append(out, f)
	}
	return out
}

func (this *generator) renderDTO(m *model) (string, used) {
	var b strings.Builder
	var u used

	fmt.Fprintf(&b, "type %sUpdate struct {\n", m.Name)

	for _, f := range updateFields(m) {
		typ := dtoType(f.Type)
		json := lowerFirst(f.Name)
		omit := "omitempty"
		if strings.HasPrefix(typ, "utils.Opt[") {
			omit = "omitzero"
			u.utils = true
		}
		if strings.Contains(typ, "time.Time") {
			u.time = true
		}
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", f.Name, typ, json+","+omit)
	}
	b.WriteString("}\n\n")
	return b.String(), u
}

func (this *generator) renderMetamodel(m *model) (string, used) {
	var b strings.Builder
	var u used
	u.specs = true

	emitted := map[string]bool{}
	this.renderAttrs(&b, m, m, "", 0, []string{m.Name}, emitted, &u)

	fmt.Fprintf(&b, "var %s_ = specs.Metamodel[%s, %sAttrs]()\n\n", m.Name, this.qual(m.Name), m.Name)
	return b.String(), u
}

func (this *generator) renderAttrs(b *strings.Builder, root, on *model, suffix string, level int, path []string, emitted map[string]bool, u *used) {
	typeName := root.Name + suffix + "Attrs"
	if emitted[typeName] {
		return
	}
	emitted[typeName] = true

	var nested []struct {
		field  field
		target *model
		suffix string
	}

	var body strings.Builder
	if suffix != "" {
		fmt.Fprintf(&body, "\tspecs.Rel[%s, %s]\n", this.qual(root.Name), this.qual(on.Name))
	}

	for _, f := range on.Fields {
		if f.Skip {
			continue
		}
		if f.isRelation() {
			if level+1 >= this.depth {
				continue
			}
			target := f.RelTarget
			if target == "" {
				target, _ = relElem(f.Type)
				if this.modelAlias != "" {
					target = strings.TrimPrefix(target, this.modelAlias+".")
				}
			}
			tm, ok := this.models[target]
			if !ok {
				continue
			}

			cycle := false
			for _, seen := range path {
				if seen == target {
					cycle = true
					break
				}
			}
			if cycle {
				continue
			}
			sub := suffix + f.Name
			fmt.Fprintf(&body, "\t%s %s%sAttrs\n", f.Name, root.Name, sub)
			nested = append(nested, struct {
				field  field
				target *model
				suffix string
			}{f, tm, sub})
			continue
		}
		if strings.Contains(f.Type, "time.Time") {
			u.time = true
		}
		fmt.Fprintf(&body, "\t%s %s\n", f.Name, attrType("specs", this.qual(root.Name), f.Type))
	}

	for _, n := range nested {
		this.renderAttrs(b, root, n.target, n.suffix, level+1, append(path, n.target.Name), emitted, u)
	}

	fmt.Fprintf(b, "type %s struct {\n%s}\n\n", typeName, body.String())
}
